function clearCaptions(v){if('caption' in v)v.caption='';if(v.type==='pair')v.items.forEach(x=>clearCaptions(x.visual));}
export function cleanSlideCopy(slides){
 for(const s of slides){
  const previousBody=s.body;
  if(s.number===1||['agenda','summary'].includes(s.kind))s.body='';
  if(Object.hasOwn(bodies,s.id))s.body=bodies[s.id];
  if(withoutCaptions.has(s.id))clearCaptions(s.visual);
  if(s.id==='З3-С07'){
   const address=s.visual.items[1].visual;
   address.columns[1]='Значение';address.rows[1][2]='Имя сервера приложения';address.rows[3][0]='Полный URL';address.rows[3][2]='Адрес карточки проекта 17';
  }
  if(s.id==='З3-С23'){s.visual.items[0].title='Псевдокод обработчика';s.visual.items[1].visual.rows[0][1]='Да, если сеанс проверен';}
  if(s.id==='З4-С15'){
   s.visual.columns[1]='Пример отчёта';s.visual.rows=s.visual.rows.filter(row=>row[0]!=='Статус примера');
   s.visual.rows.find(row=>row[0]==='Фактически')[1]='201; заявка создана';
  }
  if(s.learning?.kind==='visual'){
   const scenario=s.learning.scenarios[0];
   if(scenario.input===previousBody)scenario.input=s.body;
   if(scenario.frames.at(-1).result===previousBody)scenario.frames.at(-1).result=s.body;
  }
 }
 return slides;
}
